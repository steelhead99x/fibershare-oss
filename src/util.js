/** Escape text for safe HTML attribute and text-node insertion. */
export function esc(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

export const EXT = ' target="_blank" rel="noopener noreferrer"';
